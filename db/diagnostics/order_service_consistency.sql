-- Read-only report. Investigate source/version before any scoped correction.
-- Completed services still within their legitimate rest interval are not stale.
SELECT
  (SELECT COUNT(*) FROM ORDER_FULFILLMENT_UNITS F JOIN ORDER_NOMINEES N ON N.ID=F.NOMINEE_ID
    WHERE F.KIND='nominee' AND F.UNIT_STATUS IN ('waiting','accepted','in_service')
      AND (NOT (F.SCHEDULED_STARTS_AT <=> N.REQUESTED_STARTS_AT)
        OR NOT (F.SCHEDULED_ENDS_AT <=> N.REQUESTED_SERVICE_ENDS_AT)
        OR NOT (DATE_ADD(F.SCHEDULED_ENDS_AT,INTERVAL F.REST_MINUTES_RESERVED MINUTE) <=> N.REQUESTED_BUSY_UNTIL))) AS ActiveProjectionMismatches,
  (SELECT COUNT(*) FROM ORDER_FULFILLMENT_UNITS F LEFT JOIN STAFF_BUSY_BLOCKS B ON B.ORDER_NOMINEE_ID=F.NOMINEE_ID AND B.BLOCK_STATUS='active'
    WHERE F.KIND='nominee' AND F.CANCELLED_QUANTITY=0 AND F.COMPLETED_QUANTITY<F.QUANTITY
      AND (F.STARTED_QUANTITY>F.COMPLETED_QUANTITY OR (F.ACCEPTED_QUANTITY>0
        AND DATE_ADD(F.SCHEDULED_ENDS_AT,INTERVAL F.REST_MINUTES_RESERVED MINUTE)>DATE_ADD(UTC_TIMESTAMP(),INTERVAL 8 HOUR)))
      AND B.ID IS NULL) AS MissingExpectedBusyBlocks,
  (SELECT COUNT(*) FROM STAFF_BUSY_BLOCKS B JOIN ORDER_NOMINEES N ON N.ID=B.ORDER_NOMINEE_ID
    JOIN ORDERS O ON O.ID=N.ORDER_ID LEFT JOIN ORDER_FULFILLMENT_UNITS F ON F.NOMINEE_ID=N.ID
    WHERE B.BLOCK_STATUS='active' AND B.ENDS_AT<=DATE_ADD(UTC_TIMESTAMP(),INTERVAL 8 HOUR)
      AND (O.ORDER_STATUS IN ('cancelled','rejected','completed') OR F.UNIT_STATUS IN ('cancelled','completed'))) AS StaleClosedBusyBlocks,
  (SELECT COUNT(*) FROM NOTIFICATION_SCHEDULES S JOIN ORDERS O ON O.ID=S.ORDER_ID
    LEFT JOIN ORDER_FULFILLMENT_UNITS F ON F.NOMINEE_ID=S.ORDER_NOMINEE_ID
    WHERE S.STATUS='pending' AND (O.ORDER_STATUS IN ('cancelled','rejected','completed','expired')
      OR F.UNIT_STATUS IN ('cancelled','completed'))) AS PendingClosedServiceReminders,
  (SELECT COUNT(*) FROM ORDER_FULFILLMENT_OPERATIONS O LEFT JOIN ORDER_FULFILLMENT_OPERATION_UNITS U
    ON U.ORDER_ID=O.ORDER_ID AND U.OPERATION_ID=O.OPERATION_ID AND U.UNIT_ID=O.UNIT_ID AND U.TARGET_KIND='unit'
    WHERE O.UNIT_ID IS NOT NULL AND U.UNIT_ID IS NULL) AS MissingHistoricalOperationLinks;

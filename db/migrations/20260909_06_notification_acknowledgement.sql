    ADD COLUMN IF NOT EXISTS `ACKNOWLEDGED_AT` DATETIME(6) NULL AFTER `READ_AT`;

ALTER TABLE `NOTIFICATION_DELIVERIES`
    ADD COLUMN IF NOT EXISTS `WITHDRAWN_AT` DATETIME(6) NULL AFTER `ACKNOWLEDGED_AT`;

ALTER TABLE `NOTIFICATION_DELIVERIES`
    ADD KEY IF NOT EXISTS `IX_NOTIFICATION_ACKNOWLEDGEMENT`

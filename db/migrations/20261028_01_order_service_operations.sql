-- Apply with the local DBA runbook before deploying dependent API code.
-- Existing single-unit operations remain readable by the previous API.
ALTER TABLE ORDER_FULFILLMENT_OPERATIONS
  MODIFY COLUMN UNIT_ID CHAR(36) NULL,
  ADD COLUMN IF NOT EXISTS OPERATION_SCOPE VARCHAR(16) NOT NULL DEFAULT 'unit';

CREATE TABLE IF NOT EXISTS ORDER_FULFILLMENT_OPERATION_UNITS (
  ORDER_ID CHAR(36) NOT NULL,
  OPERATION_ID CHAR(36) NOT NULL,
  UNIT_ID CHAR(36) NOT NULL,
  TARGET_KIND VARCHAR(16) NOT NULL DEFAULT 'unit',
  PRIMARY KEY (ORDER_ID, OPERATION_ID, TARGET_KIND, UNIT_ID),
  KEY IX_OPERATION_TARGET (TARGET_KIND, UNIT_ID),
  CONSTRAINT FK_OPERATION_UNITS_PARENT FOREIGN KEY (ORDER_ID, OPERATION_ID)
    REFERENCES ORDER_FULFILLMENT_OPERATIONS (ORDER_ID, OPERATION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO ORDER_FULFILLMENT_OPERATION_UNITS (ORDER_ID, OPERATION_ID, UNIT_ID, TARGET_KIND)
SELECT ORDER_ID, OPERATION_ID, UNIT_ID, 'unit'
FROM ORDER_FULFILLMENT_OPERATIONS WHERE UNIT_ID IS NOT NULL
ON DUPLICATE KEY UPDATE UNIT_ID=VALUES(UNIT_ID);

-- Replace the old unique key in the same ALTER. Adding another unique key alone
-- would still collapse a batch's events into the first person's event.
ALTER TABLE ORDER_FULFILLMENT_EVENTS
  DROP INDEX UK_FULFILLMENT_EVENT_OPERATION,
  ADD UNIQUE KEY UK_FULFILLMENT_EVENT_OPERATION (ORDER_ID, OPERATION_ID, UNIT_ID, EVENT_TYPE);

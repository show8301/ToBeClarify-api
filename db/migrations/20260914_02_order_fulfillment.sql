-- S0-3. Existing orders remain flow version 1; initialize units only in the transaction creating flow version 2 orders.
CREATE TABLE IF NOT EXISTS `ORDER_FULFILLMENT_UNITS` (
  `ID` CHAR(36) NOT NULL PRIMARY KEY,
  `ORDER_ID` CHAR(36) NOT NULL,
  `BUSINESS_PERIOD_ID` CHAR(36) NULL,
  `ORDER_ITEM_ID` CHAR(36) NULL,
  `NOMINEE_ID` CHAR(36) NULL,
  `RELATED_ID` CHAR(36) NULL,
  `KIND` VARCHAR(24) NOT NULL,
  `NAME_SNAPSHOT` VARCHAR(300) NOT NULL,
  `STAFF_ID` CHAR(36) NULL,
  `QUANTITY` INT NOT NULL,
  `ACCEPTED_QUANTITY` INT NOT NULL DEFAULT 0,
  `STARTED_QUANTITY` INT NOT NULL DEFAULT 0,
  `COMPLETED_QUANTITY` INT NOT NULL DEFAULT 0,
  `CANCELLED_QUANTITY` INT NOT NULL DEFAULT 0,
  `UNIT_STATUS` VARCHAR(24) NOT NULL DEFAULT 'waiting',
  `ORIGINAL_AMOUNT` INT NOT NULL,
  `ORIGINAL_CREDIT` INT NOT NULL DEFAULT 0,
  `CANCELLED_AMOUNT` INT NOT NULL DEFAULT 0,
  `RETURNED_CREDIT` INT NOT NULL DEFAULT 0,
  `PURCHASED_MINUTES` INT NOT NULL DEFAULT 0,
  `SCHEDULED_STARTS_AT` DATETIME(6) NULL,
  `SCHEDULED_ENDS_AT` DATETIME(6) NULL,
  `ACTUAL_STARTS_AT` DATETIME(6) NULL,
  `ACTUAL_ENDS_AT` DATETIME(6) NULL,
  `VERSION` INT NOT NULL DEFAULT 1,
  `CREATED_AT` DATETIME(6) NOT NULL,
  `UPDATED_AT` DATETIME(6) NOT NULL,
  UNIQUE KEY `UK_FULFILLMENT_ITEM` (`ORDER_ID`, `ORDER_ITEM_ID`),
  UNIQUE KEY `UK_FULFILLMENT_NOMINEE` (`NOMINEE_ID`),
  KEY `IX_FULFILLMENT_PERIOD` (`BUSINESS_PERIOD_ID`, `UNIT_STATUS`),
  KEY `IX_FULFILLMENT_STAFF` (`STAFF_ID`, `UNIT_STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS `ORDER_FULFILLMENT_OPERATIONS` (
  `ORDER_ID` CHAR(36) NOT NULL,
  `OPERATION_ID` CHAR(36) NOT NULL,
  `UNIT_ID` CHAR(36) NOT NULL,
  `PAYLOAD_HASH` CHAR(64) NOT NULL,
  `RESULT_JSON` LONGTEXT NOT NULL,
  `ACTOR_ID` CHAR(36) NOT NULL,
  `CREATED_AT` DATETIME(6) NOT NULL,
  PRIMARY KEY (`ORDER_ID`, `OPERATION_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

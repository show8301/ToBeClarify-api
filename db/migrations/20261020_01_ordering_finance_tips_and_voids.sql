-- Add payroll-only tip supplements and auditable voids for mistaken cash records.
-- Existing records remain active and unchanged.
ALTER TABLE `ORDERING_FINANCE_RECORDS`
    ADD COLUMN IF NOT EXISTS `VOIDED_AT` DATETIME(6) NULL,
    ADD COLUMN IF NOT EXISTS `VOIDED_BY` VARCHAR(36) NULL,
    ADD COLUMN IF NOT EXISTS `VOID_REASON` VARCHAR(500) NULL,
    ADD COLUMN IF NOT EXISTS `TIP_DISTRIBUTION_MODE` VARCHAR(16) NULL,
    ADD COLUMN IF NOT EXISTS `LINKED_CASH_RECORD_ID` VARCHAR(36) NULL,
    ADD KEY IF NOT EXISTS `IX_ORDERING_FINANCE_RECORDS_VOIDED` (`SESSION_ID`, `VOIDED_AT`);

CREATE TABLE IF NOT EXISTS `ORDERING_FINANCE_TIP_ALLOCATIONS` (
    `ID` VARCHAR(36) NOT NULL,
    `RECORD_ID` VARCHAR(36) NOT NULL,
    `STAFF_ID` VARCHAR(36) NOT NULL,
    `STAFF_NAME_SNAPSHOT` VARCHAR(100) NOT NULL,
    `PERCENTAGE` DECIMAL(9,4) NULL,
    `AMOUNT` BIGINT NOT NULL,
    `CREATED_AT` DATETIME(6) NOT NULL,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UX_ORDERING_FINANCE_TIP_ALLOCATIONS_RECORD_STAFF` (`RECORD_ID`, `STAFF_ID`),
    KEY `IX_ORDERING_FINANCE_TIP_ALLOCATIONS_STAFF` (`STAFF_ID`, `CREATED_AT`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

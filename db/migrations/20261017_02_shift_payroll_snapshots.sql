-- Apply before the matching API release. Existing settled payroll is not recalculated.
CREATE TABLE IF NOT EXISTS STAFF_PAYROLL_SNAPSHOTS (
  STAFF_MEMBER_ID CHAR(36) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  DUTY_PLAN_ID CHAR(36) NULL,
  PAYROLL_ROLE VARCHAR(16) NULL,
  CAN_USE_BACKSTAGE BOOLEAN NOT NULL DEFAULT FALSE,
  BACKSTAGE_PARTICIPANT BOOLEAN NOT NULL DEFAULT FALSE,
  STARTED_AT DATETIME NOT NULL,
  VERSION INT NOT NULL DEFAULT 1,
  CONFIRMED_AT DATETIME NULL,
  CONFIRMED_BY VARCHAR(100) NULL,
  PRIMARY KEY (STAFF_MEMBER_ID, BUSINESS_DATE)
);

CREATE TABLE IF NOT EXISTS STAFF_PAYROLL_SNAPSHOT_AUDIT (
  ID CHAR(36) NOT NULL PRIMARY KEY,
  STAFF_MEMBER_ID CHAR(36) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  BEFORE_ROLE VARCHAR(16) NULL,
  AFTER_ROLE VARCHAR(16) NOT NULL,
  SNAPSHOT_VERSION INT NOT NULL,
  REASON VARCHAR(500) NOT NULL,
  CREATED_AT DATETIME NOT NULL,
  CREATED_BY VARCHAR(100) NOT NULL,
  KEY IX_PAYROLL_AUDIT_STAFF_DATE (STAFF_MEMBER_ID, BUSINESS_DATE)
);

-- Old attendance cannot prove which role was confirmed at the time of starting.
-- Seed an unresolved marker rather than copying today's mutable duty plan.
INSERT IGNORE INTO STAFF_PAYROLL_SNAPSHOTS
  (STAFF_MEMBER_ID, BUSINESS_DATE, DUTY_PLAN_ID, STARTED_AT)
SELECT STAFF_MEMBER_ID, BUSINESS_DATE, MAX(DUTY_PLAN_ID), MIN(EVENT_AT)
FROM STAFF_ATTENDANCE_EVENTS
WHERE EVENT_TYPE IN ('clock_in', 'scheduled_start', 'manual_interval')
GROUP BY STAFF_MEMBER_ID, BUSINESS_DATE;

ALTER TABLE SETTLEMENT_STAFF_INPUTS
  ADD COLUMN IF NOT EXISTS PAYROLL_SNAPSHOT_VERSION INT NULL;
ALTER TABLE SETTLEMENT_RUNS
  ADD COLUMN IF NOT EXISTS CALCULATION_VERSION INT NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS INPUT_VERSION INT NOT NULL DEFAULT 0;

ALTER TABLE SETTLEMENT_ATTENDANCE_BACKFILL_REQUESTS
  ADD COLUMN IF NOT EXISTS PAYROLL_SNAPSHOT_VERSION INT NULL;

-- Phase 1: additive schema only. No historical receipts or inferred fee seed.
-- Apply through docs/DATABASE-MIGRATION-RUNBOOK.md before the dependent API.
CREATE TABLE IF NOT EXISTS ORDERING_ADMISSION_POLICY (
    ID VARCHAR(16) NOT NULL,
    ADMISSION_AMOUNT BIGINT NULL,
    VERSION BIGINT NOT NULL DEFAULT 0,
    UPDATED_AT DATETIME(6) NULL,
    UPDATED_BY VARCHAR(36) NULL,
    PRIMARY KEY (ID),
    CONSTRAINT CK_ADMISSION_POLICY_SINGLETON CHECK (ID = 'default'),
    CONSTRAINT CK_ADMISSION_POLICY_AMOUNT CHECK (ADMISSION_AMOUNT IS NULL OR ADMISSION_AMOUNT BETWEEN 0 AND 1000000000000),
    CONSTRAINT CK_ADMISSION_POLICY_VERSION CHECK (VERSION >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT IGNORE INTO ORDERING_ADMISSION_POLICY (ID) VALUES ('default');

CREATE TABLE IF NOT EXISTS ORDERING_ADMISSION_POLICY_AUDIT (
    ID VARCHAR(36) NOT NULL,
    POLICY_VERSION BIGINT NOT NULL,
    BEFORE_AMOUNT BIGINT NULL,
    AFTER_AMOUNT BIGINT NULL,
    REASON VARCHAR(500) NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UX_ADMISSION_POLICY_AUDIT_VERSION (POLICY_VERSION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Only committed phase-2 creations insert rows, in the SAME transaction as
-- session, admission, finance and credit. No tokens or credentials are stored.
CREATE TABLE IF NOT EXISTS ORDERING_SESSION_CREATE_OPERATIONS (
    OPERATION_ID CHAR(36) NOT NULL,
    PAYLOAD_HASH CHAR(64) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    ADMISSION_ID VARCHAR(36) NOT NULL,
    BUSINESS_PERIOD_ID VARCHAR(36) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    POLICY_VERSION BIGINT NOT NULL,
    PRICING_REVISION CHAR(64) NOT NULL,
    ADMISSION_AMOUNT BIGINT NOT NULL,
    DISCOUNT_AMOUNT BIGINT NOT NULL,
    MEAL_CREDIT_AMOUNT INT NOT NULL,
    ADMISSION_STATUS VARCHAR(24) NOT NULL,
    RECEIVED_AMOUNT BIGINT NOT NULL,
    CHARGE_RECORD_ID VARCHAR(36) NULL,
    RECEIPT_RECORD_ID VARCHAR(36) NULL,
    CASH_PERIOD_ID VARCHAR(36) NULL,
    ACCOUNT_VERSION BIGINT NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    PRIMARY KEY (OPERATION_ID),
    UNIQUE KEY UX_SESSION_CREATE_OPERATIONS_SESSION (SESSION_ID),
    UNIQUE KEY UX_SESSION_CREATE_OPERATIONS_ADMISSION (ADMISSION_ID),
    KEY IX_SESSION_CREATE_OPERATIONS_PERIOD (BUSINESS_PERIOD_ID, CREATED_AT),
    CONSTRAINT CK_SESSION_CREATE_OPERATION_AMOUNTS CHECK (
        ADMISSION_AMOUNT BETWEEN 0 AND 1000000000000
        AND DISCOUNT_AMOUNT BETWEEN 0 AND ADMISSION_AMOUNT
        AND MEAL_CREDIT_AMOUNT >= 0 AND RECEIVED_AMOUNT >= 0
        AND (RECEIVED_AMOUNT = 0 OR (RECEIPT_RECORD_ID IS NOT NULL AND CASH_PERIOD_ID IS NOT NULL))),
    CONSTRAINT CK_SESSION_CREATE_OPERATION_RECEIPT CHECK (
        (ADMISSION_STATUS = 'received' AND RECEIVED_AMOUNT = ADMISSION_AMOUNT - DISCOUNT_AMOUNT)
        OR (ADMISSION_STATUS = 'unpaid' AND RECEIVED_AMOUNT = 0)
        OR (ADMISSION_STATUS = 'waived' AND DISCOUNT_AMOUNT = ADMISSION_AMOUNT AND RECEIVED_AMOUNT = 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

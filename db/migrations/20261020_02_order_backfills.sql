-- Additive metadata: old orders and settlement snapshots remain unchanged.
CREATE TABLE IF NOT EXISTS ORDER_BACKFILLS (
    ORDER_ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    OPERATION_ID VARCHAR(36) NOT NULL,
    PAYLOAD_HASH CHAR(64) NOT NULL,
    DUPLICATE_HASH CHAR(64) NOT NULL,
    OCCURRED_AT DATETIME(6) NOT NULL,
    REASON VARCHAR(500) NOT NULL,
    LINKED_CASH_RECORD_ID VARCHAR(36) NULL,
    SNAPSHOT_JSON LONGTEXT NOT NULL,
    CREATED_AT DATETIME(6) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    APPLIED_SETTLEMENT_ID VARCHAR(36) NULL,
    PRIMARY KEY (ORDER_ID),
    UNIQUE KEY UX_ORDER_BACKFILLS_OPERATION (OPERATION_ID),
    UNIQUE KEY UX_ORDER_BACKFILLS_DUPLICATE (SESSION_ID, DUPLICATE_HASH),
    KEY IX_ORDER_BACKFILLS_SESSION (SESSION_ID, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Adds the presentation fields required by the current ToBeClarify web mock data.
-- This script is safe to run against the existing initial database.
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;
SET time_zone = '+08:00';

ALTER TABLE `STAFF_MEMBERS`
    ADD COLUMN IF NOT EXISTS `TODAY_SHIFT` VARCHAR(40) NULL AFTER `STATUS_TEXT`;

ALTER TABLE `STAFF_SERVICES`
    ADD COLUMN IF NOT EXISTS `SERVICE_TYPE` VARCHAR(20) NOT NULL DEFAULT 'special' AFTER `STAFF_ID`;

CREATE TABLE IF NOT EXISTS `STAFF_GALLERY_ITEMS` (
    `ID` VARCHAR(40) NOT NULL,
    `STAFF_ID` VARCHAR(40) NOT NULL,
    `IMAGE_URL` VARCHAR(500) NOT NULL,
    `SORT_ORDER` INT NOT NULL DEFAULT 0,
    `IS_PUBLISHED` BOOLEAN NOT NULL DEFAULT TRUE,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`ID`),
    KEY `IX_STAFF_GALLERY_STAFF` (`STAFF_ID`, `IS_PUBLISHED`, `SORT_ORDER`),
    CONSTRAINT `CK_STAFF_GALLERY_SORT_ORDER` CHECK (`SORT_ORDER` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE `GALLERY_ALBUMS`
    ADD COLUMN IF NOT EXISTS `PERIOD_TEXT` VARCHAR(80) NULL AFTER `COVER_IMAGE_URL`,
    ADD COLUMN IF NOT EXISTS `ENDS_AT` DATETIME NULL AFTER `PERIOD_TEXT`,
    ADD COLUMN IF NOT EXISTS `DETAIL_CONTENT` JSON NULL AFTER `ENDS_AT`;

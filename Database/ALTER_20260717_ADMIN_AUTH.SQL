-- Adds backend authentication accounts for the first admin login slice.
-- Passwords are stored as PBKDF2-HMAC-SHA256 verifiers, never as plaintext.
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;
SET time_zone = '+08:00';

CREATE TABLE IF NOT EXISTS `ADMIN_USERS` (
    `ID` VARCHAR(40) NOT NULL,
    `LOGIN_NAME` VARCHAR(80) NOT NULL,
    `DISPLAY_NAME` VARCHAR(60) NOT NULL,
    `PASSWORD_HASH` VARCHAR(255) NOT NULL,
    `ROLE_LEVEL` VARCHAR(20) NOT NULL,
    `STAFF_MEMBER_ID` VARCHAR(40) NULL,
    `IS_ACTIVE` BOOLEAN NOT NULL DEFAULT TRUE,
    `TOKEN_VERSION` INT NOT NULL DEFAULT 1,
    `LAST_LOGIN_AT` DATETIME NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`ID`),
    UNIQUE KEY `UQ_ADMIN_USERS_LOGIN_NAME` (`LOGIN_NAME`),
    KEY `IX_ADMIN_USERS_ACTIVE_ROLE` (`IS_ACTIVE`, `ROLE_LEVEL`),
    KEY `IX_ADMIN_USERS_STAFF` (`STAFF_MEMBER_ID`),
    CONSTRAINT `CK_ADMIN_USERS_ROLE_LEVEL` CHECK (`ROLE_LEVEL` IN ('developer', 'manager', 'clerk')),
    CONSTRAINT `CK_ADMIN_USERS_TOKEN_VERSION` CHECK (`TOKEN_VERSION` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
